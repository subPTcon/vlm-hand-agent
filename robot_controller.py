import numpy as np


class RobotController:

    def __init__(self, env):
        self.env = env

        # 1.0 = 打开夹爪
        # -1.0 = 关闭夹爪
        self.gripper = 1.0


    # ========================================================
    # 底层动作执行
    # ========================================================

    def _execute(self, action, steps=6):

        action = np.array(
            action,
            dtype=np.float32
        )

        for _ in range(steps):

            self.env.step(action)

            self.env.render()


    # ========================================================
    # 停止移动
    # ========================================================

    def stop(self, steps=5):

        self._execute(
            [
                0,
                0,
                0,

                0,
                0,
                0,

                self.gripper,
            ],
            steps
        )


    # ========================================================
    # X+
    # ========================================================

    def move_x_positive(self):

        self._execute(
            [
                0.12,
                0,
                0,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # X-
    # ========================================================

    def move_x_negative(self):

        self._execute(
            [
                -0.12,
                0,
                0,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # Y+
    # ========================================================

    def move_y_positive(self):

        self._execute(
            [
                0,
                0.12,
                0,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # Y-
    # ========================================================

    def move_y_negative(self):

        self._execute(
            [
                0,
                -0.12,
                0,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # 上升
    # ========================================================

    def move_up(self):

        self._execute(
            [
                0,
                0,
                0.12,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # 下降
    # ========================================================

    def move_down(self):

        self._execute(
            [
                0,
                0,
                -0.12,

                0,
                0,
                0,

                self.gripper,
            ]
        )


    # ========================================================
    # 打开夹爪
    # ========================================================

    def open_gripper(self):

        self.gripper = 1.0

        self.stop(
            steps=20
        )


    # ========================================================
    # 关闭夹爪
    # ========================================================

    def close_gripper(self):

        self.gripper = -1.0

        self.stop(
            steps=20
        )